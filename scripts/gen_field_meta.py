#!/usr/bin/env python3
"""Generate the field metadata table (independence task 2.1) from a rippled source tree.

rippled gives every serialized field flags that decide where it goes in a transaction's metadata
(ApplyStateTable::apply, src/libxrpl/ledger/ApplyStateTable.cpp in 3.4.1):
  - PreviousFields of a ModifiedNode or DeletedNode: kSmdChangeOrig, when the value changed;
  - FinalFields of a ModifiedNode: kSmdAlways or kSmdChangeNew;
  - FinalFields of a DeletedNode: kSmdAlways or kSmdDeleteFinal;
  - NewFields of a CreatedNode: kSmdCreate or kSmdAlways, when the value is not the default.

This reads include/xrpl/protocol/SField.h (the STI_* type codes and the kSmd* flag values) and
include/xrpl/protocol/detail/sfields.macro (every field), and prints
crates/xrpl-ledger/src/ledger/field_meta/table.rs. Like the amendment lists, regenerate it at each
rippled upgrade:

    python3 scripts/gen_field_meta.py <rippled tree> > crates/xrpl-ledger/src/ledger/field_meta/table.rs

It refuses a tree whose two source files differ from its git HEAD, and any field line it cannot read.
"""
import re
import subprocess
import sys
from pathlib import Path

SFIELD_H = "include/xrpl/protocol/SField.h"
SFIELDS_MACRO = "include/xrpl/protocol/detail/sfields.macro"
OUT = "crates/xrpl-ledger/src/ledger/field_meta/table.rs"


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def git(tree, *args):
    r = subprocess.run(["git", "-C", str(tree), *args], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed in {tree}: {r.stderr.strip()}")
    return r.stdout.strip()


def type_codes(header):
    codes = {name: int(code) for name, code in re.findall(r"STYPE\(STI_(\w+),\s*(-?\d+)\)", header)}
    if not codes:
        sys.exit("SField.h has no STYPE(STI_...) codes")
    return codes


def or_of(expr, flags, where):
    """The value of a kSmd expression: literals and earlier flags joined by '|'."""
    value = 0
    for term in expr.split("|"):
        term = term.strip().removeprefix("SField::")
        if re.fullmatch(r"0[xX][0-9a-fA-F]+|\d+", term):
            value |= int(term, 0)
        elif term in flags:
            value |= flags[term]
        else:
            sys.exit(f"{where}: cannot read the flag term {term!r}")
    return value


def flag_values(header):
    """kSmd* name -> value, in SField.h's order."""
    flags = {}
    for name, expr in re.findall(r"static\s+constexpr\s+auto\s+(kSmd\w+)\s*=\s*([^;]+);", strip_comments(header)):
        flags[name] = or_of(expr, flags, name)
    for need in ("kSmdNever", "kSmdChangeOrig", "kSmdChangeNew", "kSmdDeleteFinal", "kSmdCreate", "kSmdAlways",
                 "kSmdDefault"):
        if need not in flags:
            sys.exit(f"SField.h defines no {need}")
    if max(flags.values()) > 0xFF:
        sys.exit("a kSmd flag no longer fits in a u8: widen FieldMeta::meta")
    return flags


def read_fields(macro, types, flags):
    body = "\n".join(line for line in strip_comments(macro).splitlines() if not line.lstrip().startswith("#"))
    out = []
    for kind, args in re.findall(r"\b(TYPED_SFIELD|UNTYPED_SFIELD)\s*\(([^()]*)\)", body):
        parts = [a.strip() for a in args.split(",")]
        if len(parts) < 3 or not parts[0].startswith("sf") or not parts[2].isdigit():
            sys.exit(f"cannot read {kind}({args})")
        name, sti, nth = parts[0][2:], parts[1], int(parts[2])
        if sti not in types:
            sys.exit(f"sf{name}: unknown type {sti}")
        meta, terms = flags["kSmdDefault"], ["kSmdDefault"]
        for extra in parts[3:]:
            if "kSmd" in extra:
                meta = or_of(extra, flags, f"sf{name}")
                terms = [t.strip().removeprefix("SField::") for t in extra.split("|")]
            elif extra.removeprefix("SField::") != "kNotSigning":
                sys.exit(f"sf{name}: unknown argument {extra!r}")
        out.append({"name": name, "sti": sti, "type_code": types[sti], "nth": nth,
                    "code": (types[sti] << 16) | nth, "meta": meta, "terms": terms})
    seen = len(re.findall(r"\b(?:TYPED_SFIELD|UNTYPED_SFIELD)\s*\(", body))
    if seen != len(out):
        sys.exit(f"read {len(out)} of {seen} field definitions")
    for key in ("name", "code"):
        values = [f[key] for f in out]
        repeated = sorted({v for v in values if values.count(v) > 1})
        if repeated:
            sys.exit(f"repeated {key}s: {repeated}")
    return sorted(out, key=lambda f: f["code"])


def rust_flag(name):
    """kSmdChangeOrig -> SMD_CHANGE_ORIG."""
    return "SMD_" + re.sub(r"(?<!^)(?=[A-Z])", "_", name.removeprefix("kSmd")).upper()


def render(version, commit, flags, fields):
    lines = [
        "// GENERATED by scripts/gen_field_meta.py: do not edit by hand.",
        f"// Source: rippled {version} ({commit}),",
        f"//   {SFIELDS_MACRO} and {SFIELD_H}.",
        "// Regenerate at each rippled upgrade:",
        f"//   python3 scripts/gen_field_meta.py <rippled tree> > {OUT}",
        "",
        "use super::FieldMeta;",
        "",
    ]
    for name, value in flags.items():
        lines.append(f"/// `SField::{name}`.")
        lines.append(f"pub const {rust_flag(name)}: u8 = 0x{value:02x};")
    lines += [
        "",
        f"/// Every field rippled {version} defines ({len(fields)}), sorted by code.",
        "#[rustfmt::skip]",
        f"pub(super) static FIELDS: [FieldMeta; {len(fields)}] = [",
    ]
    sti = None
    for f in fields:
        if f["sti"] != sti:
            sti = f["sti"]
            lines.append(f"    // STI_{sti} ({f['type_code']})")
        meta = " | ".join(rust_flag(t) for t in f["terms"])
        code = f"0x{f['code'] >> 16:04x}_{f['code'] & 0xFFFF:04x}"
        lines.append(f"    FieldMeta {{ code: {code}, type_code: {f['type_code']}, nth: {f['nth']}, "
                     f"name: \"{f['name']}\", meta: {meta} }},")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    tree = Path(argv[0]).expanduser()
    dirty = git(tree, "status", "--porcelain", "--", SFIELD_H, SFIELDS_MACRO)
    if dirty:
        sys.exit(f"{tree}: the source files differ from HEAD:\n{dirty}")
    version = git(tree, "describe", "--tags", "--always")
    commit = git(tree, "rev-parse", "HEAD")
    header = (tree / SFIELD_H).read_text()
    flags = flag_values(header)
    fields = read_fields((tree / SFIELDS_MACRO).read_text(), type_codes(header), flags)
    sys.stdout.write(render(version, commit, flags, fields))
    print(f"{len(fields)} fields, {len(flags)} flags from rippled {version} ({commit[:12]})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
